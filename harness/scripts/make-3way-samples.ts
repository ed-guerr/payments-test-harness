#!/usr/bin/env -S npx tsx
/**
 * make-3way-samples.ts — build the committed 10-run three-way sample reports.
 *
 * A deterministic file transform over already-collected eval data. No LLM,
 * no network, no re-runs: it reads the local full-fidelity reports
 * (gitignored — they contain raw LAN endpoints and personal paths), and
 * writes the committed trimmed + scrubbed samples to artifacts/eval/:
 *
 *   sample-Qwen3.8-27B-3way.json/.md  from 2026-10-17T01-33-40-Qwen3.8-27B.json
 *   sample-gemma-12b-3way.json/.md    from 2026-10-17T09-10-49--mnt-ai-models-Gemma4-12.json
 *   sample-gpt-6-luna-3way.json/.md   from 2026-10-17T22-58-19-gpt-6-luna.json,
 *       with three infra-hit (task, condition) pairs taken WHOLE from the
 *       patch runs (STITCH below) — the documented provenance of 79/86/90.
 *
 * Transform order per model:
 *   1. stitch (Luna only) — pairs replaced per STITCH; summary recomputed
 *      from the stitched runs via summarize()
 *   2. trim   — trace tool-result text capped at 200 chars (+ marker);
 *               finalText capped at 500; agent-authored suite JSON in
 *               create_suite/update_suite args kept intact
 *   3. scrub  — every string through redactPersonal (home dir, repo root,
 *               model path) then redact (RFC1918 endpoints, credentials)
 *   4. write  — JSON + markdown (toMarkdown applies redact as a second pass)
 *
 * Sanity checks (the script fails loudly instead of writing a plausible
 * wrong sample if the local reports no longer match the documented story):
 *   - each source: 330 runs, 110 per variant; patch files cover exactly
 *     the documented pairs with zero agentError runs
 *   - Luna main: exactly three infra-error runs (fetch/timeout), one in
 *     each stitched pair, none elsewhere
 *   - final per-condition pass counts match the README tables
 *     (EXPECTED_PASS below)
 *
 * Same inputs → byte-identical outputs (no timestamps are generated).
 *
 * Usage: npm run samples:3way   (from harness/)
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { summarize, toMarkdown } from "../src/eval/report";
import { modelLabel, redact, redactPersonal } from "../src/eval/tracereport";
import type { EvalReport, TaskRunRecord } from "../src/eval/types";

const TRUNC_MARKER = "…[truncated in sample]";
const TRACE_TEXT_CAP = 200;
const FINAL_TEXT_CAP = 500;

/** Luna stitch policy: infra-hit pairs taken whole from patch runs. */
const STITCH: Array<{ task: string; variant: string; patch: string }> = [
  { task: "double-settle-rejection", variant: "kb-on", patch: "2026-10-18T00-16-01-gpt-6-luna.json" },
  { task: "interleaved-payments", variant: "kb-on", patch: "2026-10-18T00-16-01-gpt-6-luna.json" },
  { task: "settle-moves-money", variant: "kb-off", patch: "2026-10-18T00-31-44-gpt-6-luna.json" },
];

/** Per-condition pass counts the README tables quote. */
const EXPECTED_PASS: Record<string, Record<string, number>> = {
  "sample-Qwen3.8-27B-3way": { "kb-on": 110, "kb-content-off": 110, "kb-off": 101 },
  "sample-gemma-12b-3way": { "kb-on": 40, "kb-content-off": 10, "kb-off": 29 },
  "sample-gpt-6-luna-3way": { "kb-on": 79, "kb-content-off": 86, "kb-off": 90 },
};

interface SourceSpec {
  sample: string; // sample file base name (without extension)
  source: string; // full-fidelity report file name under artifacts/eval/
  note: string; // committed sampleNote
  /** raw model id → display label for the .md header (JSON keeps the raw id) */
  displayModel?: string;
}

